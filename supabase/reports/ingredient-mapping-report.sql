-- Ingredient mapping report (G1): which recipe and protein swap items map to which canonical ingredient, and which
-- items are not mapped yet. Prints Markdown, one line per row.
--
--   DATABASE_URL=postgresql://... npm run ingredients:report     (writes docs/ingredient-mapping-report.md)
--
-- Read only. Run it against a database with every migration applied; the checked-in report comes from a fresh one
-- (seeded recipes, no protein swaps). Lines are sorted in Lithuanian order, so the output is the same on every run.

\pset format unaligned
\pset tuples_only on
\pset footer off

with categories (category, position, label) as (
  -- INGREDIENT_CATEGORIES in shared/utils/ingredient.ts, in list order.
  values
    ('fruit_and_vegetables', 1, 'Fruit and vegetables'),
    ('meat_and_fish', 2, 'Meat and fish'),
    ('dairy_and_eggs', 3, 'Dairy and eggs'),
    ('grains_and_bread', 4, 'Grains and bread'),
    ('pantry', 5, 'Pantry'),
    ('frozen', 6, 'Frozen'),
    ('other', 7, 'Other')
),
recipe_items as (
  select item, count(*) as uses, count(distinct recipe_id) as recipes
  from public.recipe_ingredients
  group by item
),
mapped_items as (
  select ingredient.category, ingredient.name, ingredient.on_shopping_list, recipe_items.item, recipe_items.uses
  from recipe_items
  join public.ingredient_aliases alias on alias.item = recipe_items.item
  join public.ingredients ingredient on ingredient.id = alias.ingredient_id
),
unmapped as (
  select source, item, uses, recipes, units from public.unmapped_ingredient_items
),
mapping_rows as (
  select
    categories.position,
    mapped_items.name,
    format(
      '| %s%s | %s |',
      mapped_items.name,
      case when mapped_items.on_shopping_list then '' else ' (not shopped)' end,
      string_agg(format('%s (%s)', mapped_items.item, mapped_items.uses), ', '
        order by mapped_items.item collate "lt-x-icu")
    ) as line
  from mapped_items
  join categories on categories.category = mapped_items.category
  group by categories.position, mapped_items.name, mapped_items.on_shopping_list
),
lines (section, position, sort_key, line) as (
  select 1, 0, '', '# Ingredient mapping report'
  union all select 1, 1, '', ''
  union all select 1, 2, '',
    'Generated by `npm run ingredients:report` (`supabase/reports/ingredient-mapping-report.sql`). Do not edit by hand.'
  union all select 1, 3, '', ''
  union all select 1, 4, '', '## Summary'
  union all select 1, 5, '', ''
  union all select 1, 6, '', format('- Distinct recipe items: %s', (select count(*) from recipe_items))
  union all select 1, 7, '', format('- Mapped to an ingredient: %s', (select count(*) from mapped_items))
  union all select 1, 8, '', format('- Not mapped: %s recipe items, %s protein swap items',
    (select count(*) from unmapped where source = 'recipe'),
    (select count(*) from unmapped where source = 'protein_swap'))
  union all select 1, 9, '', format('- Canonical ingredients: %s (%s)',
    (select count(*) from public.ingredients),
    (select string_agg(format('%s %s', lower(categories.label), counts.total), ', ' order by categories.position)
     from categories
     join (select category, count(*) as total from public.ingredients group by category) counts
       on counts.category = categories.category))
  union all select 1, 10, '', format('- Aliases: %s', (select count(*) from public.ingredient_aliases))
  union all select 1, 11, '', ''
  union all select 2, 0, '', '## Not mapped'
  union all select 2, 1, '', ''
  union all select 2, 2, '', case when exists (select 1 from unmapped)
    then '| Source | Item | Uses | Recipes | Units |'
    else 'None: every item has an ingredient.' end
  union all select 2, 3, '', '|---|---|---|---|---|' where exists (select 1 from unmapped)
  union all
  select 2, 4, source || ' ' || item,
    format('| %s | %s | %s | %s | %s |', source, item, uses, recipes, array_to_string(units, ', '))
  from unmapped
  union all select 2, 5, '', ''
  union all select 3, 0, '', '## Mapping by category'
  union all select 3, 1, '', ''
  union all select 3, 2, '', 'Each ingredient with the recipe items mapped to it and how often each is used.'
  union all
  select 4, categories.position * 10, '', format(E'\n### %s\n\n| Ingredient | Recipe items |\n|---|---|',
    categories.label)
  from categories
  where exists (select 1 from mapping_rows where mapping_rows.position = categories.position)
  union all
  select 4, mapping_rows.position * 10 + 1, mapping_rows.name, mapping_rows.line
  from mapping_rows
)
select line
from lines
order by section, position, sort_key collate "lt-x-icu";
