-- Missing translations report (X1b): how much of the recipe content (recipes, their lines, canonical ingredients,
-- tips) has a row in each language, and what is still missing. Prints Markdown, one line per row.
--
--   DATABASE_URL=postgresql://... npm run translations:report     (writes docs/missing-translations-report.md)
--
-- Read only. Run it against a database with every migration applied; the checked-in report comes from a fresh one.
-- Recipe lines are listed once per item and language, with how many lines and recipes use it. Lines are sorted in
-- Lithuanian order, so the output is the same on every run.

\pset format unaligned
\pset tuples_only on
\pset footer off

with locales (locale, position, label) as (
  -- The app's languages (nuxt.config.ts), as the translation tables' *_locale_supported checks.
  values ('lt', 1, 'Lithuanian'), ('en', 2, 'English')
),
kinds (kind, position, label) as (
  values
    ('recipe', 1, 'Recipes'),
    ('recipe_instructions', 2, 'Recipe instructions'),
    ('recipe_ingredient', 3, 'Recipe lines'),
    ('ingredient', 4, 'Ingredients'),
    ('tip', 5, 'Tips')
),
totals (kind, total) as (
  select 'recipe', count(*) from public.recipes
  union all select 'recipe_instructions', count(*) from public.recipes where btrim(instructions) <> ''
  union all select 'recipe_ingredient', count(*) from public.recipe_ingredients
  union all select 'ingredient', count(*) from public.ingredients
  union all select 'tip', count(*) from public.tips
),
missing as (
  select kind, locale, context, source_text from public.missing_content_translations
),
missing_counts as (
  select kind, locale, count(*) as missing_count from missing group by kind, locale
),
-- A recipe line is listed by its item: the same item in many recipes is one row to translate.
missing_rows as (
  select kind, locale, source_text, string_agg(distinct context, ', ' order by context) as context, count(*) as uses
  from missing
  where kind <> 'recipe_ingredient'
  group by kind, locale, source_text
  union all
  select kind, locale, source_text, format('Recipes: %s', count(distinct context)), count(*)
  from missing
  where kind = 'recipe_ingredient'
  group by kind, locale, source_text
),
lines (section, position, sort_key, line) as (
  select 1, 0, '', '# Missing translations report'
  union all select 1, 1, '', ''
  union all select 1, 2, '',
    'Generated by `npm run translations:report` (`supabase/reports/missing-translations-report.sql`). Do not edit by hand.'
  union all select 1, 3, '', ''
  union all select 1, 4, '', '## Summary'
  union all select 1, 5, '', ''
  union all select 1, 6, '', 'Translated of all, per language. Lithuanian rows mirror the source text.'
  union all select 1, 7, '', ''
  union all select 1, 8, '', '| Content | ' || (select string_agg(label, ' | ' order by position) from locales) || ' |'
  union all select 1, 9, '', '|---|' || (select string_agg('---|', '' order by position) from locales)
  union all
  select 1, 10 + kinds.position, '',
    format('| %s | %s |', kinds.label, string_agg(
      format('%s of %s', totals.total - coalesce(missing_counts.missing_count, 0), totals.total), ' | '
      order by locales.position))
  from kinds
  join totals on totals.kind = kinds.kind
  cross join locales
  left join missing_counts on missing_counts.kind = kinds.kind and missing_counts.locale = locales.locale
  group by kinds.position, kinds.label
  union all select 1, 20, '', ''
  union all select 2, 0, '', '## Missing'
  union all select 2, 1, '', ''
  union all select 2, 2, '', case when exists (select 1 from missing)
    then '| Language | Content | Lithuanian text | Where | Uses |'
    else 'None: everything is translated in every language.' end
  union all select 2, 3, '', '|---|---|---|---|---|' where exists (select 1 from missing)
  union all
  select 2, 4, format('%s %s %s', locales.position, kinds.position, missing_rows.source_text),
    format('| %s | %s | %s | %s | %s |', locales.label, kinds.label,
      replace(missing_rows.source_text, '|', '\|'), missing_rows.context, missing_rows.uses)
  from missing_rows
  join locales on locales.locale = missing_rows.locale
  join kinds on kinds.kind = missing_rows.kind
)
select line
from lines
order by section, position, sort_key collate "lt-x-icu";
