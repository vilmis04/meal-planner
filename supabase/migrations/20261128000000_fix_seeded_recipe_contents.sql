-- Seeded recipe contents fixed against the source slides (plan: "Plan: fix seeded recipe mismatches").
--
-- The two seed migrations hold 123 recipes. Checked against the meal-plan slides, many of them had estimated rather
-- than copied amounts (most of 20261012000100_seed_recipes_and_tips.sql, which is plan C's content), one recipe had
-- no ingredients or steps, and 34 recipes from the slides were never seeded. This migration:
--   * fixes 43 recipes to their slide: lines, amounts, steps, macros, portion days (and three name typos);
--   * stores counted items as pieces, the unit rules below, also in 15 recipes that otherwise match;
--   * deletes "Avižinė košė su grūdėta varške" (breakfast), which has no ingredients and no steps;
--   * adds 42 recipes: the 34 missing ones and 8 other versions of dishes that several plans make differently.
--
-- Unit rules (the plan's section 4):
--   U1 a count on the slide is stored in vnt., even when the slide also gives a weight: ½ avokado (60 g) → 0.5 vnt.;
--   U2 bread is stored as slices: item "<bread> duonos riekelė", unit vnt.;
--   U3 a spoon with a weight ("Du šaukštai miltų (40g)") is stored as the weight;
--   U4 a weight alone stays a weight;
--   U5 no amount on the slide ("šiek tiek", optional items) is stored with no amount;
--   U6 a range is stored as its midpoint (2–3 → 2.5), as the seeds already do;
--   U7 a 2-day recipe stores the whole batch, because the shopping list splits each line over portion_days: a
--      slide's "per portion" serving extra is doubled.
--
-- Rows are kept, not re-created: a fixed recipe keeps its id and its lines keep theirs (matched by position), so meal
-- plan slots, ratings, protein swaps and translations stay attached. A line past a recipe's new last position is
-- deleted, and its translation and any protein-swap item for it go with it (a swap regenerates on its own: it stores
-- a hash of the recipe's ingredients). Shopping lists of plans that use a changed or deleted recipe are marked stale
-- and rebuild when next opened.
--
-- English: every new or changed Lithuanian text gets its English text here, so the missing translations report stays
-- empty. A line's English item is the English text the same Lithuanian item already has elsewhere, or the one given
-- with its new alias below. The 'lt' rows follow by the mirror triggers.
--
-- Re-runnable: recipes are found by their current or their new name, new rows are upserted, and the same target is
-- written again. A recipe, an item alias or an English text that cannot be found aborts the migration.

