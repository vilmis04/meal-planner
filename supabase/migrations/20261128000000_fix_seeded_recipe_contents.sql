-- Apply.
do $$
declare
  missing text;
  stale_plan_ids uuid[];
begin
  -- Ingredients, their English names and the aliases.
  insert into public.ingredients (name, category)
  select name, category from fix_new_ingredients
  on conflict (name) do update set category = excluded.category;

  insert into public.ingredient_translations (ingredient_id, locale, name)
  select ingredient.id, 'en', fix.en_name
  from fix_new_ingredients fix
  join public.ingredients ingredient on ingredient.name = fix.name
  on conflict (ingredient_id, locale) do update set name = excluded.name;

  select string_agg(fix.ingredient_name, ', ') into missing
  from fix_new_aliases fix
  where not exists (select 1 from public.ingredients ingredient where ingredient.name = fix.ingredient_name);
  if missing is not null then
    raise exception 'fix_seeded_recipe_contents: no canonical ingredient named %', missing;
  end if;

  insert into public.ingredient_aliases (item, ingredient_id)
  select fix.item, ingredient.id
  from fix_new_aliases fix
  join public.ingredients ingredient on ingredient.name = fix.ingredient_name
  on conflict (item) do update set ingredient_id = excluded.ingredient_id;

  select string_agg(distinct line.item, ', ') into missing
  from fix_lines line
  where not exists (select 1 from public.ingredient_aliases alias where alias.item = line.item);
  if missing is not null then
    raise exception 'fix_seeded_recipe_contents: items without an ingredient alias: %', missing;
  end if;

  -- Each target item's English text: given with its alias above, or the one the same item already has.
  create temporary table fix_item_english on commit drop as
  select item.item,
         coalesce(
           (select fix.en_item from fix_new_aliases fix where fix.item = item.item),
           (select min(translation.item)
            from public.recipe_ingredients line
            join public.recipe_ingredient_translations translation
              on translation.recipe_ingredient_id = line.id and translation.locale = 'en'
            where line.item = item.item)
         ) as en_item
  from (select distinct item from fix_lines) item;

  select string_agg(item, ', ') into missing from fix_item_english where en_item is null;
  if missing is not null then
    raise exception 'fix_seeded_recipe_contents: items without an English text: %', missing;
  end if;

  select string_agg(name, ', ') into missing
  from fix_recipes
  where (instructions is null) <> (en_instructions is null)
     or (is_new and (en_name is null or instructions is null or portion_days is null or main_proteins is null));
  if missing is not null then
    raise exception 'fix_seeded_recipe_contents: recipes missing a value or an English text: %', missing;
  end if;

  -- The plans whose shopping lists change: plans using a recipe this migration changes or deletes.
  select array_agg(distinct slot.plan_id) into stale_plan_ids
  from public.meal_plan_slots slot
  join public.recipes recipe on recipe.id = slot.recipe_id
  where (recipe.meal_type, recipe.name) in (
          select meal_type, name from fix_recipes where not is_new
          union select meal_type, new_name from fix_recipes where new_name is not null
          union select meal_type, recipe_name from fix_lines
          union select 'breakfast'::public.meal_type, 'Avižinė košė su grūdėta varške');

  -- The recipe with no ingredients and no steps.
  delete from public.recipes
  where meal_type = 'breakfast' and name = 'Avižinė košė su grūdėta varške';

  -- Fixed recipes, found by their current or their new name.
  select string_agg(fix.name, ', ') into missing
  from fix_recipes fix
  where not fix.is_new
    and not exists (
      select 1 from public.recipes recipe
      where recipe.meal_type = fix.meal_type and recipe.name in (fix.name, coalesce(fix.new_name, fix.name)));
  if missing is not null then
    raise exception 'fix_seeded_recipe_contents: recipes not found: %', missing;
  end if;

  update public.recipes recipe
  set name          = coalesce(fix.new_name, fix.name),
      calories_kcal = coalesce(fix.calories_kcal, recipe.calories_kcal),
      carbohydrates = coalesce(fix.carbohydrates, recipe.carbohydrates),
      protein       = coalesce(fix.protein, recipe.protein),
      fat           = coalesce(fix.fat, recipe.fat),
      portion_days  = coalesce(fix.portion_days, recipe.portion_days),
      main_proteins = coalesce(fix.main_proteins, recipe.main_proteins),
      instructions  = coalesce(fix.instructions, recipe.instructions)
  from fix_recipes fix
  where not fix.is_new
    and recipe.meal_type = fix.meal_type
    and recipe.name in (fix.name, coalesce(fix.new_name, fix.name));

  -- New recipes.
  insert into public.recipes
    (name, meal_type, instructions, calories_kcal, carbohydrates, protein, fat, portion_days, main_proteins)
  select name, meal_type, instructions, calories_kcal, carbohydrates, protein, fat, portion_days, main_proteins
  from fix_recipes
  where is_new
  on conflict (name, meal_type) do update
  set instructions  = excluded.instructions,
      calories_kcal = excluded.calories_kcal,
      carbohydrates = excluded.carbohydrates,
      protein       = excluded.protein,
      fat           = excluded.fat,
      portion_days  = excluded.portion_days,
      main_proteins = excluded.main_proteins;

  -- English recipe rows: a new name or steps replace the English ones, the rest stays.
  insert into public.recipe_translations (recipe_id, locale, name, instructions)
  select recipe.id, 'en',
         coalesce(fix.en_name, existing.name),
         coalesce(fix.en_instructions, existing.instructions, '')
  from fix_recipes fix
  join public.recipes recipe
    on recipe.meal_type = fix.meal_type and recipe.name = coalesce(fix.new_name, fix.name)
  left join public.recipe_translations existing on existing.recipe_id = recipe.id and existing.locale = 'en'
  where fix.en_name is not null or fix.en_instructions is not null
  on conflict (recipe_id, locale) do update
  set name = excluded.name, instructions = excluded.instructions;

  -- Lines: every listed recipe must exist by now.
  select string_agg(distinct line.recipe_name, ', ') into missing
  from fix_lines line
  where not exists (
    select 1 from public.recipes recipe
    where recipe.meal_type = line.meal_type and recipe.name = line.recipe_name);
  if missing is not null then
    raise exception 'fix_seeded_recipe_contents: line targets for unknown recipes: %', missing;
  end if;

  create temporary table fix_line_targets on commit drop as
  select recipe.id as recipe_id, line.position, line.item, line.amount, line.unit, english.en_item
  from fix_lines line
  join public.recipes recipe on recipe.meal_type = line.meal_type and recipe.name = line.recipe_name
  join fix_item_english english on english.item = line.item;

  -- Lines past a recipe's new last position go, with their translations and swap items.
  delete from public.recipe_ingredients ingredient
  where ingredient.recipe_id in (select recipe_id from fix_line_targets)
    and not exists (
      select 1 from fix_line_targets target
      where target.recipe_id = ingredient.recipe_id and target.position = ingredient.position);

  update public.recipe_ingredients ingredient
  set item = target.item, amount = target.amount, unit = target.unit
  from fix_line_targets target
  where ingredient.recipe_id = target.recipe_id
    and ingredient.position = target.position
    and (ingredient.item, ingredient.amount, ingredient.unit)
        is distinct from (target.item, target.amount, target.unit);

  insert into public.recipe_ingredients (recipe_id, position, item, amount, unit)
  select recipe_id, position, item, amount, unit
  from fix_line_targets target
  where not exists (
    select 1 from public.recipe_ingredients ingredient
    where ingredient.recipe_id = target.recipe_id and ingredient.position = target.position);

  -- English line rows. A line whose item did not change keeps its English row as it is (one carries its own unit).
  insert into public.recipe_ingredient_translations (recipe_ingredient_id, locale, item, unit)
  select ingredient.id, 'en', target.en_item, null
  from fix_line_targets target
  join public.recipe_ingredients ingredient
    on ingredient.recipe_id = target.recipe_id and ingredient.position = target.position
  on conflict (recipe_ingredient_id, locale) do update
  set item = excluded.item,
      unit = case when recipe_ingredient_translations.item = excluded.item
                  then recipe_ingredient_translations.unit end
  where recipe_ingredient_translations.item is distinct from excluded.item;

  if stale_plan_ids is not null then
    perform public.mark_shopping_lists_stale(stale_plan_ids);
  end if;
end;
